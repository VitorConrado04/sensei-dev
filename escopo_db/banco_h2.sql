-- --- Usuarios e perfis ------------------------------------------------------

CREATE TABLE IF NOT EXISTS usuario (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    senha          VARCHAR(255) NOT NULL,
    semestre_atual INT,
    foto_url       VARCHAR(500),
    status         VARCHAR(20)  NOT NULL DEFAULT 'ATIVO',
    tipo           VARCHAR(20)  NOT NULL DEFAULT 'MENTORANDO',
    criado_em      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuario_tipo CHECK(tipo IN('ADMIN', 'MENTOR', 'MENTORANDO'))
    );

CREATE TABLE IF NOT EXISTS mentor_perfil (
    id              INT PRIMARY KEY,
    descricao       VARCHAR(1000),
    experiencia     VARCHAR(1000),
    nota_media      DECIMAL(3, 2) NOT NULL DEFAULT 0,
    total_mentorias INT           NOT NULL DEFAULT 0,
    CONSTRAINT fk_mentor_perfil_usuario
    FOREIGN KEY (id) REFERENCES usuario (id) ON DELETE CASCADE
    );

CREATE TABLE IF NOT EXISTS mentorando_perfil (
    id        INT PRIMARY KEY,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mentorando_perfil_usuario
    FOREIGN KEY (id) REFERENCES usuario (id) ON DELETE CASCADE
    );

-- --- Disciplinas -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS disciplina (
id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
nome     VARCHAR(150) NOT NULL,
semestre INT          NOT NULL
    );

CREATE TABLE IF NOT EXISTS mentor_disciplina (
    mentor_id     INT NOT NULL,
    disciplina_id INT NOT NULL,
    PRIMARY KEY (mentor_id, disciplina_id),
    CONSTRAINT fk_mentor_disciplina_mentor
    FOREIGN KEY (mentor_id) REFERENCES mentor_perfil (id),
    CONSTRAINT fk_mentor_disciplina_disciplina
    FOREIGN KEY (disciplina_id) REFERENCES disciplina (id)
    );

CREATE TABLE IF NOT EXISTS mentorando_disciplina_interesse (
    mentorando_id INT NOT NULL,
    disciplina_id INT NOT NULL,
    PRIMARY KEY (mentorando_id, disciplina_id),
    CONSTRAINT fk_interesse_mentorando
    FOREIGN KEY (mentorando_id) REFERENCES mentorando_perfil (id),
    CONSTRAINT fk_interesse_disciplina
    FOREIGN KEY (disciplina_id) REFERENCES disciplina (id)
    );

-- --- Favoritos ---------------------------------------------------------------

CREATE TABLE IF NOT EXISTS favorito (
    mentorando_id INT       NOT NULL,
    mentor_id     INT       NOT NULL,
    criado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (mentorando_id, mentor_id),
    CONSTRAINT fk_favorito_mentorando
    FOREIGN KEY (mentorando_id) REFERENCES mentorando_perfil (id),
    CONSTRAINT fk_favorito_mentor
    FOREIGN KEY (mentor_id) REFERENCES mentor_perfil (id)
    );

-- --- Agenda ------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS disponibilidade (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id   INT         NOT NULL,
    dia_semana  INT         NOT NULL,
    hora_inicio VARCHAR(5)  NOT NULL,               -- 'HH:mm'
    hora_fim    VARCHAR(5)  NOT NULL,               -- 'HH:mm'
    ativo       BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_disponibilidade_mentor
    FOREIGN KEY (mentor_id) REFERENCES mentor_perfil (id)
    );

CREATE TABLE IF NOT EXISTS bloqueio_horario (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id   INT          NOT NULL,
    data        DATE         NOT NULL,
    hora_inicio VARCHAR(5),                         -- vazio = dia inteiro bloqueado
    hora_fim    VARCHAR(5),
    motivo      VARCHAR(255),
    CONSTRAINT fk_bloqueio_horario_mentor
    FOREIGN KEY (mentor_id) REFERENCES mentor_perfil (id)
    );

-- --- Mentorias e avaliacoes --------------------------------------------------

CREATE TABLE IF NOT EXISTS mentoria (
    id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id          INT          NOT NULL,
    mentorando_id      INT          NOT NULL,
    disciplina_id      INT          NOT NULL,
    mentoria_origem_id INT,
    objetivo           VARCHAR(500) NOT NULL,
    data_hora_inicio   TIMESTAMP    NOT NULL,
    data_hora_fim      TIMESTAMP    NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    criado_em          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mentoria_mentor
    FOREIGN KEY (mentor_id) REFERENCES mentor_perfil (id),
    CONSTRAINT fk_mentoria_mentorando
    FOREIGN KEY (mentorando_id) REFERENCES mentorando_perfil (id),
    CONSTRAINT fk_mentoria_disciplina
    FOREIGN KEY (disciplina_id) REFERENCES disciplina (id),
    CONSTRAINT fk_mentoria_origem
    FOREIGN KEY (mentoria_origem_id) REFERENCES mentoria (id),
    CONSTRAINT ck_mentoria_periodo
    CHECK (data_hora_fim > data_hora_inicio)
    );

CREATE TABLE IF NOT EXISTS avaliacao (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentoria_id         INT           NOT NULL UNIQUE,
    clareza             INT           NOT NULL,
    dominio_assunto     INT           NOT NULL,
    pontualidade        INT           NOT NULL,
    capacidade_orientar INT           NOT NULL,
    experiencia_geral   INT           NOT NULL,
    nota_final          DECIMAL(3, 2) NOT NULL,
    comentario          VARCHAR(1000),
    criado_em           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_avaliacao_mentoria
    FOREIGN KEY (mentoria_id) REFERENCES mentoria (id),
    CONSTRAINT ck_avaliacao_clareza             CHECK (clareza             BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_dominio_assunto     CHECK (dominio_assunto     BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_pontualidade        CHECK (pontualidade        BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_capacidade_orientar CHECK (capacidade_orientar BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_experiencia_geral   CHECK (experiencia_geral   BETWEEN 1 AND 5)
    );

-- --- Materiais e notificacoes ------------------------------------------------

CREATE TABLE IF NOT EXISTS material (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id   INT          NOT NULL,
    mentoria_id INT,
    titulo      VARCHAR(150) NOT NULL,
    descricao   VARCHAR(500),
    arquivo_url VARCHAR(500) NOT NULL,
    criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_material_mentor
    FOREIGN KEY (mentor_id) REFERENCES mentor_perfil (id),
    CONSTRAINT fk_material_mentoria
    FOREIGN KEY (mentoria_id) REFERENCES mentoria (id)
    );

CREATE TABLE IF NOT EXISTS notificacao (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  INT          NOT NULL,
    mentoria_id INT,
    tipo        VARCHAR(30)  NOT NULL,
    mensagem    VARCHAR(500) NOT NULL,
    lida        BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notificacao_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_notificacao_mentoria
    FOREIGN KEY (mentoria_id) REFERENCES mentoria (id)
    );

