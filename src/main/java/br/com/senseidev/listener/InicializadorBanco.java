package br.com.senseidev.listener;

import br.com.senseidev.util.Conexao;

import javax.servlet.ServletContextEvent;
import javax.servlet.ServletContextListener;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import br.com.senseidev.auth.SenhaUtil;
import java.sql.ResultSet;

/** Garante a existência das tabelas principais sem apagar ou recriar dados existentes. */
public class InicializadorBanco implements ServletContextListener {
    private static final String[] ESTRUTURA = {
            "CREATE TABLE IF NOT EXISTS usuario (" +
                    "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "nome VARCHAR(150) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE, " +
                    "senha VARCHAR(255) NOT NULL, semestre_atual INT, foto_url VARCHAR(500), " +
                    "status VARCHAR(20) NOT NULL DEFAULT 'ATIVO', criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)",
            "CREATE TABLE IF NOT EXISTS mentor_perfil (" +
                    "id INT PRIMARY KEY, descricao VARCHAR(1000), experiencia VARCHAR(1000), " +
                    "nota_media DECIMAL(3,2) NOT NULL DEFAULT 0, total_mentorias INT NOT NULL DEFAULT 0, " +
                    "CONSTRAINT fk_mentor_perfil_usuario FOREIGN KEY (id) REFERENCES usuario(id) ON DELETE CASCADE)",
            "CREATE TABLE IF NOT EXISTS mentorando_perfil (" +
                    "id INT PRIMARY KEY, criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, " +
                    "CONSTRAINT fk_mentorando_perfil_usuario FOREIGN KEY (id) REFERENCES usuario(id) ON DELETE CASCADE)",
            "CREATE TABLE IF NOT EXISTS disciplina (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(150) NOT NULL, semestre INT NOT NULL)",
            "CREATE TABLE IF NOT EXISTS mentor_disciplina (mentor_id INT NOT NULL, disciplina_id INT NOT NULL, " +
                    "PRIMARY KEY (mentor_id, disciplina_id), FOREIGN KEY (mentor_id) REFERENCES mentor_perfil(id), " +
                    "FOREIGN KEY (disciplina_id) REFERENCES disciplina(id))",
            "CREATE TABLE IF NOT EXISTS mentorando_disciplina_interesse (mentorando_id INT NOT NULL, disciplina_id INT NOT NULL, " +
                    "PRIMARY KEY (mentorando_id, disciplina_id), FOREIGN KEY (mentorando_id) REFERENCES mentorando_perfil(id), " +
                    "FOREIGN KEY (disciplina_id) REFERENCES disciplina(id))",
            "CREATE TABLE IF NOT EXISTS favorito (mentorando_id INT NOT NULL, mentor_id INT NOT NULL, " +
                    "criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (mentorando_id, mentor_id), " +
                    "FOREIGN KEY (mentorando_id) REFERENCES mentorando_perfil(id), FOREIGN KEY (mentor_id) REFERENCES mentor_perfil(id))",
            "CREATE TABLE IF NOT EXISTS disponibilidade (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "mentor_id INT NOT NULL, dia_semana INT NOT NULL, hora_inicio VARCHAR(5) NOT NULL, " +
                    "hora_fim VARCHAR(5) NOT NULL, ativo BOOLEAN NOT NULL DEFAULT TRUE, " +
                    "FOREIGN KEY (mentor_id) REFERENCES mentor_perfil(id))",
            "CREATE TABLE IF NOT EXISTS bloqueio_horario (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "mentor_id INT NOT NULL, data DATE NOT NULL, hora_inicio VARCHAR(5), hora_fim VARCHAR(5), motivo VARCHAR(255), " +
                    "FOREIGN KEY (mentor_id) REFERENCES mentor_perfil(id))",
            "CREATE TABLE IF NOT EXISTS mentoria (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, mentor_id INT NOT NULL, " +
                    "mentorando_id INT NOT NULL, disciplina_id INT NOT NULL, mentoria_origem_id INT, objetivo VARCHAR(500) NOT NULL, " +
                    "data_hora_inicio TIMESTAMP NOT NULL, data_hora_fim TIMESTAMP NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE', " +
                    "criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, " +
                    "FOREIGN KEY (mentor_id) REFERENCES mentor_perfil(id), FOREIGN KEY (mentorando_id) REFERENCES mentorando_perfil(id), " +
                    "FOREIGN KEY (disciplina_id) REFERENCES disciplina(id), FOREIGN KEY (mentoria_origem_id) REFERENCES mentoria(id), " +
                    "CHECK (data_hora_fim > data_hora_inicio))",
            "CREATE TABLE IF NOT EXISTS avaliacao (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, mentoria_id INT NOT NULL UNIQUE, " +
                    "clareza INT NOT NULL CHECK (clareza BETWEEN 1 AND 5), dominio_assunto INT NOT NULL CHECK (dominio_assunto BETWEEN 1 AND 5), " +
                    "pontualidade INT NOT NULL CHECK (pontualidade BETWEEN 1 AND 5), capacidade_orientar INT NOT NULL CHECK (capacidade_orientar BETWEEN 1 AND 5), " +
                    "experiencia_geral INT NOT NULL CHECK (experiencia_geral BETWEEN 1 AND 5), nota_final DECIMAL(3,2) NOT NULL, " +
                    "comentario VARCHAR(1000), criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (mentoria_id) REFERENCES mentoria(id))",
            "CREATE TABLE IF NOT EXISTS material (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, mentor_id INT NOT NULL, mentoria_id INT, " +
                    "titulo VARCHAR(150) NOT NULL, descricao VARCHAR(500), arquivo_url VARCHAR(500) NOT NULL, " +
                    "criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (mentor_id) REFERENCES mentor_perfil(id), " +
                    "FOREIGN KEY (mentoria_id) REFERENCES mentoria(id))",
            "CREATE TABLE IF NOT EXISTS notificacao (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario_id INT NOT NULL, mentoria_id INT, " +
                    "tipo VARCHAR(30) NOT NULL, mensagem VARCHAR(500) NOT NULL, lida BOOLEAN NOT NULL DEFAULT FALSE, " +
                    "criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (usuario_id) REFERENCES usuario(id), " +
                    "FOREIGN KEY (mentoria_id) REFERENCES mentoria(id))"
    };

    private static final String[][] DISCIPLINAS_BASE = {
            {"Algoritmos e Lógica de Programação", "1"}, {"Fundamentos de Sistemas de Informação", "1"},
            {"Programação Orientada a Objetos", "2"}, {"Estrutura de Dados", "2"},
            {"Banco de Dados", "2"}, {"Desenvolvimento de Sistemas Web", "3"},
            {"Engenharia de Software", "3"}, {"Infraestrutura de TI", "3"},
            {"Redes de Computadores", "4"}, {"Segurança da Informação", "4"}
    };

    @Override
    public void contextInitialized(ServletContextEvent event) {
        try (Connection c = Conexao.abrir(event.getServletContext()); Statement st = c.createStatement()) {
            // Coluna TIPO da tabela USUARIO (ADMIN, MENTOR ou MENTORANDO).
            st.execute("ALTER TABLE usuario ADD COLUMN IF NOT EXISTS tipo VARCHAR(20) NOT NULL DEFAULT 'MENTORANDO'");
            st.execute("ALTER TABLE usuario ADD CONSTRAINT IF NOT EXISTS ck_usuario_tipo CHECK (tipo IN ('ADMIN', 'MENTOR', 'MENTORANDO'))");
            // Preenche o tipo de quem ja estava cadastrado, olhando em qual tabela de perfil a pessoa esta
            st.execute("UPDATE usuario SET tipo = 'MENTOR' WHERE id IN (SELECT id FROM mentor_perfil)");
            st.execute("UPDATE usuario SET tipo = 'MENTORANDO' WHERE id IN (SELECT id FROM mentorando_perfil)");

            for (String sql : ESTRUTURA) st.execute(sql);
            criarAdminInicial(c);
            criarDisciplinasBase(c);
            event.getServletContext().log("Banco Sensei.dev verificado; tabelas existentes foram preservadas.");
        } catch (SQLException e) {
            event.getServletContext().log("Falha ao preparar o banco H2 do Sensei.dev.", e);
            throw new IllegalStateException("Não foi possível preparar o banco de dados Sensei.dev.", e);
        }
    }

    @Override
    public void contextDestroyed(ServletContextEvent sce) {

    }

    // Admin nao tem tela de cadastro: ele e criado aqui, uma unica vez, quando o Tomcat sobe.
    // Se o e-mail ja existir, nao faz nada (por isso pode rodar a cada inicializacao)
    private void criarAdminInicial(Connection c) throws SQLException {
        String adminEmail = "admin@sensei.dev";
        String adminSenha = "admin12345";

        // 1) ve se o admin ja existe
        try (PreparedStatement ps = c.prepareStatement("SELECT 1 FROM usuario WHERE email = ?")) {
            ps.setString(1, adminEmail);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) return;
            }

        }
        // 2) nao existe: cria com a senha em hash (nunca a senha pura no banco)
        String sql = "INSERT INTO usuario (nome, email, senha, status, tipo) VALUES (?, ?, ?, 'ATIVO', 'ADMIN')";
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, "Administrador");
            ps.setString(2, adminEmail);
            ps.setString(3, SenhaUtil.gerarHash(adminSenha));
            ps.executeUpdate();
        }
    }


    private void criarDisciplinasBase(Connection c) throws SQLException {
        String sql = "INSERT INTO disciplina (nome, semestre) SELECT ?, ? WHERE NOT EXISTS " +
                "(SELECT 1 FROM disciplina WHERE LOWER(nome)=LOWER(?))";
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            for (String[] disciplina : DISCIPLINAS_BASE) {
                ps.setString(1, disciplina[0]);
                ps.setInt(2, Integer.parseInt(disciplina[1]));
                ps.setString(3, disciplina[0]);
                ps.executeUpdate();
            }
        }
    }
}